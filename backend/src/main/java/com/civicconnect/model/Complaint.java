package com.civicconnect.model;

import com.civicconnect.enums.ComplaintCategory;
import com.civicconnect.enums.ComplaintStatus;
import jakarta.persistence.*;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.OffsetDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

/**
 * A citizen complaint reported to the municipal authority.
 *
 * <p>A complaint can be submitted by a registered citizen (non-null
 * {@link #submittedBy}) or anonymously (null {@link #submittedBy} and
 * an optional {@link #submitterContact}). Anonymous complainants receive
 * a {@link #trackingCode} — a one-time secret UUID — shown at submission
 * time, which they use to track or reopen their complaint.
 *
 * <p>Status changes are immutably recorded in {@link ComplaintStatusHistory}.
 * The most recent status is always the value of {@link #status}; the history
 * table is the authoritative audit trail.
 *
 * <p>Table: {@code complaints}
 */
@Entity
@Table(name = "complaints", indexes = {
        @Index(name = "idx_complaints_status",       columnList = "status"),
        @Index(name = "idx_complaints_submitted_by", columnList = "submitted_by"),
        @Index(name = "idx_complaints_reference",    columnList = "reference_number"),
        @Index(name = "idx_complaints_tracking_code",columnList = "tracking_code")
})
public class Complaint {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "id", nullable = false, updatable = false)
    private UUID id;

    /**
     * Human-readable complaint reference number (e.g. {@code CC-2026-0001}).
     * Generated by {@code ComplaintService} before the entity is persisted.
     * Unique across all complaints and safe to share publicly.
     */
    @Column(name = "reference_number", nullable = false, unique = true, length = 20)
    private String referenceNumber;

    /**
     * Secret UUID shown to the submitter exactly once when the complaint is
     * created. Required to track or reopen an anonymous complaint.
     * Not returned in list responses; only in the submission confirmation.
     */
    @Column(name = "tracking_code", nullable = false, unique = true, length = 64)
    private String trackingCode;

    @Column(name = "title", nullable = false, length = 255)
    private String title;

    @Enumerated(EnumType.STRING)
    @Column(name = "category", nullable = false, length = 50)
    private ComplaintCategory category;

    @Column(name = "description", nullable = false, columnDefinition = "TEXT")
    private String description;

    /** Ward or locality name as entered by the citizen. */
    @Column(name = "locality", nullable = false, length = 255)
    private String locality;

    /** Optional nearby landmark to help field teams locate the issue. */
    @Column(name = "landmark", length = 255)
    private String landmark;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 30)
    private ComplaintStatus status = ComplaintStatus.SUBMITTED;

    /**
     * The registered citizen who submitted this complaint.
     * Null for anonymous submissions.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "submitted_by")
    private User submittedBy;

    /**
     * Optional contact information for anonymous complainants
     * (email address or phone number). Never returned to other users.
     */
    @Column(name = "submitter_contact", length = 255)
    private String submitterContact;

    /** Department currently responsible for resolving this complaint. */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "assigned_department_id")
    private Department assignedDepartment;

    /**
     * Latest officer-provided note visible to the citizen on the tracking page.
     * Updated each time a status change with a note is saved.
     */
    @Column(name = "remarks", columnDefinition = "TEXT")
    private String remarks;

    /** Full, ordered status history. Populated lazily to avoid N+1 on list queries. */
    @OneToMany(mappedBy = "complaint", cascade = CascadeType.ALL, fetch = FetchType.LAZY)
    @OrderBy("changedAt ASC")
    private List<ComplaintStatusHistory> statusHistory = new ArrayList<>();

    /** Photo and file attachments uploaded with or after submission. */
    @OneToMany(mappedBy = "complaint", cascade = CascadeType.ALL, fetch = FetchType.LAZY)
    private List<ComplaintAttachment> attachments = new ArrayList<>();

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private OffsetDateTime createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private OffsetDateTime updatedAt;

    // ── Constructors ─────────────────────────────────────────────────────────

    protected Complaint() {
        // Required by JPA
    }

    public Complaint(String referenceNumber,
                     String trackingCode,
                     String title,
                     ComplaintCategory category,
                     String description,
                     String locality) {
        this.referenceNumber = referenceNumber;
        this.trackingCode    = trackingCode;
        this.title           = title;
        this.category        = category;
        this.description     = description;
        this.locality        = locality;
    }

    // ── Getters ──────────────────────────────────────────────────────────────

    public UUID getId() { return id; }
    public String getReferenceNumber() { return referenceNumber; }
    public String getTrackingCode() { return trackingCode; }
    public String getTitle() { return title; }
    public ComplaintCategory getCategory() { return category; }
    public String getDescription() { return description; }
    public String getLocality() { return locality; }
    public String getLandmark() { return landmark; }
    public ComplaintStatus getStatus() { return status; }
    public User getSubmittedBy() { return submittedBy; }
    public String getSubmitterContact() { return submitterContact; }
    public Department getAssignedDepartment() { return assignedDepartment; }
    public String getRemarks() { return remarks; }
    public List<ComplaintStatusHistory> getStatusHistory() { return statusHistory; }
    public List<ComplaintAttachment> getAttachments() { return attachments; }
    public OffsetDateTime getCreatedAt() { return createdAt; }
    public OffsetDateTime getUpdatedAt() { return updatedAt; }

    // ── Setters ──────────────────────────────────────────────────────────────

    public void setTitle(String title) { this.title = title; }
    public void setCategory(ComplaintCategory category) { this.category = category; }
    public void setDescription(String description) { this.description = description; }
    public void setLocality(String locality) { this.locality = locality; }
    public void setLandmark(String landmark) { this.landmark = landmark; }
    public void setStatus(ComplaintStatus status) { this.status = status; }
    public void setSubmittedBy(User submittedBy) { this.submittedBy = submittedBy; }
    public void setSubmitterContact(String submitterContact) { this.submitterContact = submitterContact; }
    public void setAssignedDepartment(Department assignedDepartment) { this.assignedDepartment = assignedDepartment; }
    public void setRemarks(String remarks) { this.remarks = remarks; }

    // ── Object methods ───────────────────────────────────────────────────────

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Complaint that)) return false;
        return id != null && id.equals(that.id);
    }

    @Override
    public int hashCode() {
        return id != null ? id.hashCode() : 0;
    }

    @Override
    public String toString() {
        return "Complaint{id=" + id
                + ", ref='" + referenceNumber + "'"
                + ", status=" + status + "}";
    }
}
